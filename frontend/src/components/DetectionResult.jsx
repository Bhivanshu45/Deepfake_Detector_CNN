import { AlertTriangle, CheckCircle2, FlaskConical, Info, RotateCcw, ShieldAlert, ShieldCheck } from 'lucide-react';
import { useCountUp } from '../hooks/useCountUp';

const RING_RADIUS = 52;
const RING_CIRCUMFERENCE = 2 * Math.PI * RING_RADIUS;

function ProbabilityBar({ label, value, tone }) {
  const animated = useCountUp(value, 1100);
  return (
    <div className={`prob prob--${tone}`}>
      <div className="prob__head">
        <span>{label}</span>
        <span className="prob__value">{animated.toFixed(2)}%</span>
      </div>
      <div
        className="prob__track"
        role="progressbar"
        aria-label={`${label} probability`}
        aria-valuemin={0}
        aria-valuemax={100}
        aria-valuenow={value}
      >
        <div className="prob__fill" style={{ '--target': `${value}%` }} />
      </div>
    </div>
  );
}

export default function DetectionResult({ result, file, previewUrl, onReset }) {
  const isFake = result.prediction === 'FAKE';
  const tone = isFake ? 'fake' : 'real';
  const confidence = useCountUp(result.confidence, 1300);
  const dashOffset = RING_CIRCUMFERENCE * (1 - confidence / 100);
  const completedAt = new Date(result.analyzed_at).toLocaleTimeString([], {
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
  });

  return (
    <article className={`result result--${tone}`} aria-labelledby="result-title">
      <div className="result__demo-banner">
        <FlaskConical size={15} aria-hidden="true" />
        <strong>SIMULATED RESULT</strong>
        <span>Demo prediction from mock data</span>
      </div>

      <header className="result__header">
        <div className="result__thumb">
          <img src={previewUrl} alt={`Analyzed image ${file.name}`} />
        </div>
        <div className="result__summary">
          <p className="result__status">
            <CheckCircle2 size={14} aria-hidden="true" /> Analysis complete · {completedAt}
          </p>
          <h3 id="result-title" className="result__verdict">
            {isFake ? <ShieldAlert size={22} aria-hidden="true" /> : <ShieldCheck size={22} aria-hidden="true" />}
            <span>
              Prediction: <span className="result__label">{result.prediction}</span>
            </span>
          </h3>
          <p className="result__desc">
            {isFake
              ? 'This image shows patterns associated with AI manipulation.'
              : 'This image appears consistent with an authentic photograph.'}
          </p>
        </div>
      </header>

      <div className="result__body">
        <div className="gauge" aria-label={`Confidence ${result.confidence.toFixed(2)} percent`} role="img">
          <svg viewBox="0 0 120 120" aria-hidden="true">
            <circle className="gauge__track" cx="60" cy="60" r={RING_RADIUS} />
            <circle
              className="gauge__value"
              cx="60"
              cy="60"
              r={RING_RADIUS}
              strokeDasharray={RING_CIRCUMFERENCE}
              strokeDashoffset={dashOffset}
            />
          </svg>
          <div className="gauge__label" aria-hidden="true">
            <span className="gauge__number">{confidence.toFixed(2)}%</span>
            <span className="gauge__caption">Confidence</span>
          </div>
        </div>

        <div className="result__probs">
          <ProbabilityBar label="Real probability" value={result.real_probability} tone="real" />
          <ProbabilityBar label="Fake probability" value={result.fake_probability} tone="fake" />
        </div>
      </div>

      <div className="result__disclaimer" role="note">
        <Info size={16} aria-hidden="true" />
        <p>
          <strong>Demo mode:</strong> this result was generated by a frontend mock service, not by the
          trained CNN model. It does not reflect the real authenticity of your image.
        </p>
      </div>

      {isFake && (
        <p className="result__caveat">
          <AlertTriangle size={14} aria-hidden="true" />
          Detector outputs should never be treated as definitive proof of manipulation.
        </p>
      )}

      <button type="button" className="btn btn--primary btn--block" onClick={onReset}>
        <RotateCcw size={17} aria-hidden="true" />
        Analyze Another Image
      </button>
    </article>
  );
}
